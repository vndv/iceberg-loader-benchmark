"""Generate docs/RESULTS.md and the README measured-result block from raw JSON.

Raw files in docs/data/*_RAW_*.json are the only source of truth. Run this
script after every benchmark run; hand-edited numbers in the docs will drift.

    .venv/bin/python gen_docs.py
"""

from __future__ import annotations

import json
import re
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DATA_DIR = ROOT / 'docs' / 'data'

# (raw file basename, section title). Order defines output order.
SECTIONS = [
    ('LOCAL_RAW_2026-10-02.json', 'Local (SQLite + filesystem)'),
    ('REST_RAW_2026-10-02.json', 'REST (Polaris + MinIO)'),
    ('PUBLIC_API_RAW_2026-10-02.json', 'Public API, 100 MiB (NYC 311)'),
    ('PUBLIC_API_1G_RAW_2026-10-02.json', 'Public API, 1 GiB (NYC 311)'),
]

WRITERS = ('iceberg-loader', 'dlt')
SCENARIO_ORDER = {'initial': 0, 'append': 1}
METRIC_KEYS = (
    'seconds',
    'peak_rss_delta_bytes',
    'table_bytes',
    'data_files',
    'snapshots',
    'local_disk_bytes',
    'remote_bytes',
)

README_BEGIN = '<!-- MEASURED:BEGIN (generated by gen_docs.py - do not edit) -->'
README_END = '<!-- MEASURED:END -->'


def human_bytes(value: float) -> str:
    if value == 0:
        return '0'
    if value >= 2**30:
        return f'{value / 2**30:.2f} GiB'
    return f'{value / 2**20:.1f} MiB'


def fmt_num(value: float) -> str:
    return str(int(value)) if float(value).is_integer() else f'{value:g}'


def group_stats(group: list[dict]) -> dict[str, dict[str, float]]:
    return {
        writer: {key: statistics.median(r[key] for r in group if r['writer'] == writer) for key in METRIC_KEYS}
        for writer in WRITERS
    }


def load_section(filename: str, title: str) -> str:
    records = [r for r in json.loads((DATA_DIR / filename).read_text()) if not r['warmup']]
    by_rows: dict[int, list[dict]] = {}
    for record in records:
        by_rows.setdefault(record['rows'], []).append(record)
    has_scenario = 'scenario' in records[0]

    lines = [f'## {title}', '']

    raw_link = f'[raw data]({DATA_DIR.name}/{filename})'
    if not has_scenario:  # public API sections carry a source snapshot
        source_file = filename.replace('RAW', 'SOURCE')
        schema_len = len(json.loads((DATA_DIR / source_file).read_text())['schema'])
        chunks = sorted({r['chunks'] for r in records})
        lines.append(
            f'Snapshot: {records[0]["source_bytes"]:,} bytes, {records[0]["rows"]:,} rows, '
            f'{schema_len} columns, {chunks[0]} chunk(s). '
            f'{raw_link} - [source metadata]({DATA_DIR.name}/{source_file}).'
        )
        lines.append('')

    groups: list[tuple[int | None, str | None, list[dict]]] = []
    for rows in sorted(by_rows):
        scenarios = sorted({r.get('scenario') for r in by_rows[rows]}, key=lambda s: (SCENARIO_ORDER.get(s, 9), str(s)))
        for scenario in scenarios:
            group = [r for r in by_rows[rows] if r.get('scenario') == scenario]
            groups.append((rows, scenario, group))

    if has_scenario:
        header = ['Rows', 'Scenario', 'Writer']
        align = ['---:', ':---', ':---']
    else:
        header = ['Writer']
        align = [':---']
    header += ['Median write time', 'Median peak RSS', 'Iceberg table', 'Files', 'Snapshots', 'Local disk', 'Remote', 'Ratio']
    align += ['---:', '---:', '---:', '---:', '---:', '---:', '---:', '---:']
    lines.append('| ' + ' | '.join(header) + ' |')
    lines.append('| ' + ' | '.join(align) + ' |')

    for rows, scenario, group in groups:
        stats = group_stats(group)
        ratio = stats['dlt']['seconds'] / stats['iceberg-loader']['seconds']
        lead = [f'{rows:,}', str(scenario)] if has_scenario else [WRITERS[0]]
        for index, writer in enumerate(WRITERS):
            s = stats[writer]
            if has_scenario:
                cells = [lead[0], lead[1] if index == 0 else '', writer]
            else:
                cells = [writer]
            cells += [
                f'{s["seconds"]:.3f} s',
                human_bytes(s['peak_rss_delta_bytes']),
                human_bytes(s['table_bytes']),
                fmt_num(s['data_files']),
                fmt_num(s['snapshots']),
                human_bytes(s['local_disk_bytes']),
                human_bytes(s['remote_bytes']),
                f'{ratio:.2f}×' if writer == 'dlt' else '',
            ]
            lines.append('| ' + ' | '.join(cells) + ' |')

    lines.append('')
    return '\n'.join(lines)


def render_results() -> str:
    parts = [
        '# Results',
        '',
        '> Tables are generated by [`gen_docs.py`](../gen_docs.py) from the raw JSON files in '
        '[docs/data](data/). Edit the raw data and rerun the script; do not edit these tables by hand.',
        '',
        'All values are medians over measured repetitions (warmup runs excluded). '
        '"Ratio" is dlt median write time divided by iceberg-loader median write time, computed from '
        'unrounded medians. What the timer covers: [Methodology](METHODOLOGY.md). '
        'Commands and per-run caveats: [Run notes](reports/RUNS.md).',
        '',
    ]
    bodies = []
    for filename, title in SECTIONS:
        path = DATA_DIR / filename
        if not path.exists():
            raise SystemExit(f'missing raw file: {path} - commit it from results/ or fix SECTIONS')
        bodies.append(load_section(filename, title))
    return '\n'.join(parts) + '\n' + '\n'.join(bodies).rstrip() + '\n'


def render_readme_block() -> str:
    filename, _ = SECTIONS[-1]
    records = [r for r in json.loads((DATA_DIR / filename).read_text()) if not r['warmup']]
    stats = group_stats(records)
    ratio = stats['dlt']['seconds'] / stats['iceberg-loader']['seconds']
    lines = [
        '## Measured result',
        '',
        f'The NYC 311 public API run used a 1 GiB CSV snapshot ({records[0]["rows"]:,} rows).',
        '',
        '| Writer | Median write time | Median peak RSS |',
        '| :--- | ---: | ---: |',
        f'| iceberg-loader | {stats["iceberg-loader"]["seconds"]:.3f} s | {human_bytes(stats["iceberg-loader"]["peak_rss_delta_bytes"])} |',
        f'| dlt | {stats["dlt"]["seconds"]:.3f} s | {human_bytes(stats["dlt"]["peak_rss_delta_bytes"])} |',
        '',
        f'In this setup, dlt took **{ratio:.2f}×** as long. The timer covers the write call only; see '
        f'[Methodology](docs/METHODOLOGY.md). Full tables for every scenario: [Results](docs/RESULTS.md) - '
        f'[raw data](docs/data/{filename}).',
        '',
    ]
    return '\n'.join(lines)


def update_readme(block: str) -> bool:
    readme = ROOT / 'README.md'
    text = readme.read_text()
    if README_BEGIN not in text or README_END not in text or text.index(README_BEGIN) > text.index(README_END):
        print('README markers not found or inverted; README left unchanged. Wrap the section with:')
        print(f'{README_BEGIN} ... {README_END}')
        return False
    pattern = re.compile(re.escape(README_BEGIN) + r'.*?' + re.escape(README_END), re.DOTALL)
    readme.write_text(pattern.sub(README_BEGIN + '\n' + block.rstrip() + '\n' + README_END, text, count=1))
    return True


def main() -> None:
    (ROOT / 'docs' / 'RESULTS.md').write_text(render_results())
    print('wrote docs/RESULTS.md')
    if update_readme(render_readme_block()):
        print('updated README.md measured-result block')


if __name__ == '__main__':
    main()